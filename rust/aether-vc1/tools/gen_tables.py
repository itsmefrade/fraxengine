#!/usr/bin/env python3
"""Generate src/tables.rs from the FFmpeg VC-1 sources (LGPL-2.1+).

Usage: gen_tables.py <ffmpeg libavcodec dir> > src/tables.rs
Only numeric C arrays are extracted; nested braces are flattened row-major.
"""
import re, sys, os

src = sys.argv[1]

def read(f):
    return open(os.path.join(src, f)).read()

def strip_comments(t):
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    t = re.sub(r'//[^\n]*', '', t)
    return t

def extract(text, name):
    text = strip_comments(text)
    m = re.search(r'\b' + re.escape(name) + r'((?:\s*\[[^\]]*\])+)\s*=\s*\{', text)
    if not m:
        raise SystemExit('missing ' + name)
    dims = re.findall(r'\[([^\]]*)\]', m.group(1))
    i = m.end() - 1
    depth = 0
    j = i
    while True:
        c = text[j]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    body = text[i:j + 1]
    sym = {'AC_MODES': 8, 'WMV1_SCANTABLE_COUNT': 4}
    dv = []
    for d in dims:
        d = d.strip()
        dv.append(int(d, 0) if re.match(r'^(0[xX][0-9a-fA-F]+|\d+)$', d) else sym[d])
    toks = re.findall(r'\{|\}|-?\s*(?:0[xX][0-9a-fA-F]+|\d+)', body)
    pos = [0]
    def parse():
        # returns nested list
        assert toks[pos[0]] == '{'
        pos[0] += 1
        items = []
        while toks[pos[0]] != '}':
            if toks[pos[0]] == '{':
                items.append(parse())
            else:
                items.append(int(toks[pos[0]].replace(' ', ''), 0))
                pos[0] += 1
        pos[0] += 1
        return items
    tree = parse()
    def flat(node, level):
        n = dv[level]
        if level == len(dv) - 1:
            vals = list(node) + [0] * (n - len(node))
            assert len(vals) == n, (name, len(node), n)
            return vals
        res = []
        node = list(node) + [[]] * (n - len(node))
        for sub in node:
            res += flat(sub, level + 1)
        return res
    return dims, flat(tree, 0)

out = []
out.append('// @generated by tools/gen_tables.py from FFmpeg libavcodec (release/7.1), LGPL-2.1-or-later.\n'
           '// Do not edit by hand.\n#![allow(dead_code)]\n')

def emit(name, ty, text, cname, fmt=None):
    dims, vals = extract(text, cname)
    bits = {'u8': 8, 'u16': 16, 'u32': 32}.get(ty)
    if bits:
        vals = [v & ((1 << bits) - 1) for v in vals]  # C unsigned wrap-around (e.g. -1 in uint8_t tables)
    out.append('pub static %s: [%s; %d] = [' % (name, ty, len(vals)))
    line = '   '
    for v in vals:
        s = ' %d,' % v
        if len(line) + len(s) > 100:
            out.append(line); line = '   '
        line += s
    out.append(line)
    out.append('];')

