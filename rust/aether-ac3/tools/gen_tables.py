#!/usr/bin/env python3
"""Regenerates src/tables_gen.rs from FFmpeg's libavcodec table sources.

Usage: gen_tables.py <dir containing eac3_data.c ac3.c ac3tab.c> > src/tables_gen.rs

The FFmpeg files are LGPL-2.1-or-later; the generated file inherits that
license (see NOTICE).
"""
import re
import sys
from pathlib import Path


def read(base, name):
    return (Path(base) / name).read_text()


def ints(body):
    return [int(x, 0) for x in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", body)]


def block(src, decl_regex):
    m = re.search(decl_regex + r"[^=]*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("table not found: " + decl_regex)
    return m.group(1)


def emit_flat(name, ty, vals, per_line=12):
    out = [f"pub const {name}: [{ty}; {len(vals)}] = ["]
    for i in range(0, len(vals), per_line):
        out.append("    " + ", ".join(str(v) for v in vals[i : i + per_line]) + ",")
    out.append("];")
    return "\n".join(out)


def emit_2d(name, ty, rows):
    w = len(rows[0])
    out = [f"pub const {name}: [[{ty}; {w}]; {len(rows)}] = ["]
    for r in rows:
        out.append("    [" + ", ".join(str(v) for v in r) + "],")
    out.append("];")
    return "\n".join(out)


def main():
    base = sys.argv[1]
    eac3 = read(base, "eac3_data.c")
    ac3 = read(base, "ac3.c")

    print("// @generated by tools/gen_tables.py from FFmpeg libavcodec tables")
    print("// (eac3_data.c, ac3.c). LGPL-2.1-or-later, see NOTICE. Do not edit.")
    print("#![allow(clippy::unreadable_literal)]")
    print()

    print(emit_flat("BITS_VS_HEBAP", "u8", ints(block(eac3, r"const uint8_t ff_eac3_bits_vs_hebap\[20\]"))))
    print()
    print(emit_flat("GAQ_REMAP_1", "i16", ints(block(eac3, r"const int16_t ff_eac3_gaq_remap_1\[12\]"))))
    print()
    for nm, key in (("GAQ_REMAP_2_4_A", "a"), ("GAQ_REMAP_2_4_B", "b")):
        v = ints(block(eac3, rf"const int16_t ff_eac3_gaq_remap_2_4_{key}\[9\]\[2\]"))
        print(emit_2d(nm, "i16", [v[i : i + 2] for i in range(0, len(v), 2)]))
        print()

    # Vector quantisation tables, hebap 1..7.
    for h in range(1, 8):
        m = re.search(rf"static const int16_t vq_hebap{h}\[(\d+)\]\[6\] = \{{(.*?)\n\}};", eac3, re.S)
        n = int(m.group(1))
        v = ints(m.group(2))
        # FFmpeg declares vq_hebap4 with 32 rows but defines 31 (the last code
        # is unused and zero-initialised there).
        v += [0] * (n * 6 - len(v))
        assert len(v) == n * 6, (h, len(v), n)
        print(emit_2d(f"VQ_HEBAP{h}", "i16", [v[i : i + 6] for i in range(0, len(v), 6)]))
        print()

    # Frame exponent strategy combinations.
    m = re.search(r"ff_eac3_frm_expstr\[32\]\[6\] = \{(.*?)\n\};", eac3, re.S)
    names = {"EXP_REUSE": 0, "EXP_D15": 1, "EXP_D25": 2, "EXP_D45": 3}
    toks = re.findall(r"EXP_\w+", m.group(1))
    v = [names[t] for t in toks]
    assert len(v) == 32 * 6
    print(emit_2d("FRM_EXPSTR", "u8", [v[i : i + 6] for i in range(0, len(v), 6)]))
    print()

    # SPX attenuation table (float literals).
    m = re.search(r"ff_eac3_spx_atten_tab\[32\]\[3\] = \{(.*?)\n\};", eac3, re.S)
    f = re.findall(r"\d+\.\d+f", m.group(1))
    assert len(f) == 96
    f = [x[:-1] for x in f]
    print("pub const SPX_ATTEN_TAB: [[f32; 3]; 32] = [")
    for i in range(0, 96, 3):
        print("    [" + ", ".join(f[i : i + 3]) + "],")
    print("];")
    print()

    # Bit allocation tables.
    print(emit_flat("LOG_ADD_TAB", "u8", ints(block(ac3, r"static const uint8_t ac3_log_add_tab\[260\]")), 16))
    print()
    v = ints(block(ac3, r"static const uint16_t ac3_hearing_threshold_tab\[AC3_CRITICAL_BANDS\]\[3\]"))
    assert len(v) == 150
    print(emit_2d("HEARING_THRESHOLD_TAB", "u16", [v[i : i + 3] for i in range(0, 150, 3)]))


main()
