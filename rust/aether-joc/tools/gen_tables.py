#!/usr/bin/env python3
"""Converts the ETSI TS 103 420 V1.2.1 table source (ts_103420_tables.c, shipped
in ts_103420v010201p0.zip next to the PDF) into src/tables_gen.rs.
Usage: python3 -I tools/gen_tables.py tools/ts_103420_tables.c src/tables_gen.rs"""
import re, sys
src = open(sys.argv[1]).read()
out = ["// @generated by tools/gen_tables.py from ETSI TS 103 420 V1.2.1 ts_103420_tables.c.",
       "// Tables are normative data of the ETSI specification; see NOTICE.", ""]
for m in re.finditer(r"const int (joc_huff_code_\w+)\[\]\[2\]\s*=\s*\{(.*?)\n\};", src, re.S):
    name = m.group(1).upper()
    pairs = re.findall(r"\{\s*(-?\d+)\s*,\s*(-?\d+)\s*\}", m.group(2))
    out.append(f"pub static {name}: [[i16; 2]; {len(pairs)}] = [")
    for i in range(0, len(pairs), 8):
        out.append("    " + " ".join(f"[{a}, {b}]," for a, b in pairs[i:i+8]))
    out.append("];\n")
m = re.search(r"const float prot64\[640\]\s*=\s*\{(.*?)\};", src, re.S)
vals = re.findall(r"[-+]?\d\.\d+e[-+]\d+", m.group(1))
assert len(vals) == 640, len(vals)
out.append("pub static QWIN: [f32; 640] = [")
for i in range(0, 640, 4):
    out.append("    " + " ".join(f"{float(v):.9e}," for v in vals[i:i+4]))
out.append("];")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
