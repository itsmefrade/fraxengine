#!/usr/bin/env python3
"""Generates src/output/hrtf_data.rs from the MIT Media Lab KEMAR diffuse-field HRTF set.

Dev-time only: downloads https://sound.media.mit.edu/resources/KEMAR/diffuse.zip with curl into a
temporary directory (the raw dataset is NOT committed), picks the measured directions the binaural
renderer needs and writes them as 16 bit integers exactly as measured (128 taps, 44.1 kHz).

    python3 -I rust/aether-audio/tools/gen_hrtf.py [path/to/diffuse.zip]

The set stores the right hemisphere only (azimuth 0..180, positive = to the listener's right); the
left hemisphere is the same responses with the ears swapped (the KEMAR set is symmetric), which the
renderer does at runtime. File names are `H<elevation>e<azimuth>a.wav`, stereo: channel 0 = left ear,
channel 1 = right ear. See src/output/NOTICE-HRTF for the licence.
"""
import os
import struct
import subprocess
import sys
import tempfile
import wave
import zipfile

URL = "https://sound.media.mit.edu/resources/KEMAR/diffuse.zip"

# (slot name, azimuth, elevation). All of these are on the measured grid (5 degree steps at
# elevation 0, 6.43 degree steps at elevation 40, so 45/90/135/180 are exact), so the nearest
# measurement is the target itself.
SLOTS = [
    ("C0", 0, 0),
    ("R15", 15, 0),
    ("R30", 30, 0),
    ("R60", 60, 0),
    ("R90", 90, 0),
    ("R110", 110, 0),
    ("R135", 135, 0),
    ("B180", 180, 0),
    ("U0", 0, 40),
    ("U45", 45, 40),
    ("U90", 90, 40),
    ("U135", 135, 40),
    ("U180", 180, 40),
    ("TOP", 0, 90),
]


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "output", "hrtf_data.rs")
    out = os.path.normpath(out)
    with tempfile.TemporaryDirectory() as tmp:
        if len(sys.argv) > 1:
            zpath = sys.argv[1]
        else:
            zpath = os.path.join(tmp, "diffuse.zip")
            subprocess.run(["curl", "-sSL", "--fail", "-o", zpath, URL], check=True)
        root = os.path.join(tmp, "kemar")
        with zipfile.ZipFile(zpath) as z:
            z.extractall(root)
        lines = []
        lines.append("// Generated by tools/gen_hrtf.py. Do not edit.")
        lines.append("// MIT Media Lab KEMAR HRTF measurements, diffuse-field equalised, 128 taps at 44.1 kHz,")
        lines.append("// right hemisphere (see NOTICE-HRTF for source and licence).")
        lines.append("")
        lines.append("pub const SOURCE_RATE: u32 = 44100;")
        lines.append("pub const TAPS: usize = 128;")
        lines.append("")
        lines.append("#[allow(dead_code)] // azimuth / elevation document the measurement")
        lines.append("pub struct Slot {")
        lines.append("    pub name: &'static str,")
        lines.append("    pub azimuth: i16,")
        lines.append("    pub elevation: i16,")
        lines.append("    pub left: [i16; TAPS],")
        lines.append("    pub right: [i16; TAPS],")
        lines.append("}")
        lines.append("")
        lines.append(f"pub static SLOTS: [Slot; {len(SLOTS)}] = [")
        for name, az, el in SLOTS:
            path = None
            for dirpath, _, files in os.walk(root):
                want = f"H{el}e{az:03d}a.wav"
                if want in files:
                    path = os.path.join(dirpath, want)
                    break
            if path is None:
                raise SystemExit(f"missing measurement elevation {el} azimuth {az}")
            with wave.open(path) as w:
                assert w.getnchannels() == 2 and w.getsampwidth() == 2 and w.getframerate() == 44100
                n = w.getnframes()
                assert n == 128, n
                data = struct.unpack("<%dh" % (n * 2), w.readframes(n))
            left, right = data[0::2], data[1::2]
            fmt = lambda v: "[" + ", ".join(str(x) for x in v) + "]"
            lines.append("    Slot {")
            lines.append(f'        name: "{name}",')
            lines.append(f"        azimuth: {az},")
            lines.append(f"        elevation: {el},")
            lines.append(f"        left: {fmt(left)},")
            lines.append(f"        right: {fmt(right)},")
            lines.append("    },")
        lines.append("];")
        with open(out, "w") as f:
            f.write("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
